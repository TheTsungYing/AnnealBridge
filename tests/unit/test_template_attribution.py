def test_constraint_term_row_maps_to_the_generating_term_template():
    # cap[i] = x[a] + x[b] + x[c] + frac[i] * x[i] <= 5: frac[a] = 0.5 puts a
    # non-integer coefficient at terms[3], generated by term template 1.
    candidate = problem(
        parameters=[
            {"name": "frac", "indices": ["item"], "default": 1,
             "values": [{"key": ["a"], "value": 0.5}]}
        ],
        constraints=[
            {"id": "explicit_first", "type": "hard",
             "terms": [{"variable": "x[a]", "coefficient": 1}], "operator": "<=", "rhs": 1}
        ],
        constraint_templates=[
            {
                "id": "cap",
                "type": "hard",
                "for_each": ["i in item"],
                "terms": [
                    {"for_each": ["j in item"], "coefficient": 1, "variable": "x[j]"},
                    {"coefficient": "frac[i]", "variable": "x[i]"},
                ],
                "operator": "<=",
                "rhs": 5,
            }
        ],
    )  # fmt: skip
    expansion = expand_problem(candidate)
    assert expansion.problem.constraints[1].terms[3].coefficient == 0.5
    assert errors_of(candidate) == [
        (
            "NON_INTEGER_INEQUALITY",
            "constraint_templates[0].terms[1]",
            "Inequality constraint cap[a] requires integer coefficients and rhs for "
            "slack encoding, got 0.5 (generated by constraint_templates[0] with i=a)",
        )
    ]


