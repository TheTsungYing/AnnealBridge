def explicit_problem(explicit: dict, *, templates: bool) -> OptimizationProblem:
    """``explicit`` alone, or with warning-free templates added after it."""
    data = {
        "version": "1.3",
        "name": "explicit entries",
        "variables": copy.deepcopy(explicit["variables"]),
        "objective": {
            "direction": "minimize",
            "linear_terms": copy.deepcopy(explicit["linear_terms"]),
        },
        "constraints": copy.deepcopy(explicit["constraints"]),
        "cardinality_constraints": copy.deepcopy(explicit["cardinality_constraints"]),
    }
    if templates:
        data["index_sets"] = [ITEM]
        data["variable_families"] = [{"name": "x", "indices": ["item"]}]
        data["objective"]["linear_term_templates"] = [
            {"for_each": ["i in item"], "coefficient": 1, "variable": "x[i]"}
        ]
        data["constraint_templates"] = [
            {"id": "pair_with_u", "type": "hard", "for_each": ["i in item"],
             "terms": [{"coefficient": 1, "variable": "x[i]"},
                       {"coefficient": 1, "variable": "u"}],
             "operator": ">=", "rhs": 1}
        ]  # fmt: skip
        data["cardinality_constraint_templates"] = [
            {"id": "one_x", "type": "hard",
             "variables": [{"for_each": ["i in item"], "variable": "x[i]"}],
             "operator": "==", "rhs": 1}
        ]  # fmt: skip
    return OptimizationProblem.model_validate(data)


def test_explicit_errors_are_the_same_with_and_without_templates():
    with_templates = explicit_problem(EXPLICIT_WITH_ERRORS, templates=True)
    without = explicit_problem(EXPLICIT_WITH_ERRORS, templates=False)
    assert with_templates.has_templates() and not without.has_templates()
    ours = validate_problem_full(with_templates)
    theirs = validate_problem_full(without)
    assert not theirs.valid
    assert {e.code for e in theirs.errors} >= {
        "UNKNOWN_VARIABLE",
        "SOFT_CONSTRAINT_MISSING_WEIGHT",
        "NON_INTEGER_INEQUALITY",
        "DUPLICATE_CONSTRAINT_ID",
        "DUPLICATE_CARDINALITY_VARIABLE",
    }
    assert ours.errors == theirs.errors
    assert validate_problem(with_templates) == validate_problem(without)


def test_explicit_warnings_are_the_same_with_and_without_templates():
    with_templates = explicit_problem(EXPLICIT_WITH_WARNINGS, templates=True)
    without = explicit_problem(EXPLICIT_WITH_WARNINGS, templates=False)
    # The templates themselves are warning-free: no expansion warning.
    assert expand_problem(with_templates).warnings == ()
    ours = validate_problem_full(with_templates)
