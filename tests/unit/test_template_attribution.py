"""Validator output on an expanded problem points back into the templates.

Schema 1.3 spec 2026-09-25 §14 (v4):

* §14.11 path mapping -- every row of the table: an issue the ordinary
  validator reports on a generated entry has its path rewritten to the
  template (``variables[k]`` -> ``variable_families[f]``, a constraint term
  ``terms[j]`` -> the term template ``terms[m]`` that generated it, ...) and
  ``(generated by <template path>)`` appended, with the outer binding
  (``with i=a``) for a generated constraint; other paths are unchanged.
* §14.11 bounded collector -- at most twenty errors per template, the rest
  counted per code on the last one listed; generated warnings aggregated per
  (code, mapped path) with the number of entries that got them.
* §14.11 special cases -- DUPLICATE_TERM_MERGED attributed to the template
  of the first generated repeat (explicit-only duplicates keep their path,
  several duplicates of one template aggregate); a cross-list
  DUPLICATE_CONSTRAINT_ID stays on the explicit entry with a note naming
  the template; UNKNOWN_VARIABLE on ``x[a, 0]`` gets the no-spaces hint;
  NO_VARIABLES says when every generated variable was left out.
* §14.8 -- with any error every warning, the expansion's own included, is
  dropped; errors and warnings of explicit entries are exactly what the
  same problem without templates gets; expansion warnings come first.
"""

import copy
import re

import pytest

from annealbridge.models import OptimizationProblem
from annealbridge.validation import (
    expand_problem,
    validate_expanded,
    validate_problem,
    validate_problem_full,
)

ITEM = {"name": "item", "elements": ["a", "b", "c"]}


def document(**extra) -> dict:
    """A 1.3 document with family x[item] and one linear term per x[i].

    ``objective`` in ``extra`` is merged into the objective; every other key
    replaces the top-level field.
    """
    data = {
        "version": "1.3",
        "name": "attribution",
        "index_sets": [ITEM],
        "variable_families": [{"name": "x", "indices": ["item"]}],
        "variables": [],
        "objective": {
            "direction": "minimize",
            "linear_terms": [],
            "linear_term_templates": [
                {"for_each": ["i in item"], "coefficient": 1, "variable": "x[i]"}
            ],
        },
        "constraints": [],
    }
    for key, value in extra.items():
        if key == "objective":
            data["objective"].update(value)
        else:
            data[key] = value
    return data


def problem(**extra) -> OptimizationProblem:
    return OptimizationProblem.model_validate(document(**extra))


def errors_of(candidate: OptimizationProblem) -> list[tuple[str, str | None, str]]:
    result = validate_problem_full(candidate)
    assert not result.valid
    assert result.warnings == []
    # The errors-only entry point reports exactly the same errors.
    assert validate_problem(candidate) == result.errors
    return [(error.code, error.path, error.message) for error in result.errors]


def warnings_of(candidate: OptimizationProblem) -> list[tuple[str, str | None, str]]:
    result = validate_problem_full(candidate)
    assert result.valid, result.errors
    return [(warning.code, warning.path, warning.message) for warning in result.warnings]


