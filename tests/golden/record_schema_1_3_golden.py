def _load_fixture(name: str) -> OptimizationProblem:
    data = json.loads((FIXTURES_DIR / name).read_text(encoding="utf-8"))
    return OptimizationProblem.model_validate(data)


def _rows(indices: int, table: dict) -> list[dict]:
    """Parameter rows from ``{key: value}``; a one-index key is a bare element."""
    return [
        {"key": list(key) if indices > 1 else [key], "value": value}
        for key, value in table.items()
    ]


def make_problem_1_3(
    *,
    name: str,
    direction: str,
    index_sets: list[dict],
    variable_families: list[dict],
    parameters: list[dict] | None = None,
    variables: list[dict] | None = None,
    linear_term_templates: list[dict] | None = None,
    quadratic_term_templates: list[dict] | None = None,
    constraint_templates: list[dict] | None = None,
    cardinality_constraint_templates: list[dict] | None = None,
) -> OptimizationProblem:
    return OptimizationProblem.model_validate(
        {
            "version": VERSION,
            "name": name,
            "index_sets": index_sets,
            "parameters": parameters or [],
            "variable_families": variable_families,
            "variables": variables or [],
            "objective": {
                "direction": direction,
                "linear_terms": [],
                "linear_term_templates": linear_term_templates or [],
                "quadratic_term_templates": quadratic_term_templates or [],
            },
            "constraints": [],
            "constraint_templates": constraint_templates or [],
            "cardinality_constraint_templates": cardinality_constraint_templates or [],
            "solver": {"backend": "exact"},
        }
    )


