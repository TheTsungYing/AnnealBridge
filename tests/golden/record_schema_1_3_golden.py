# Three nodes on a cyclic ring of integer elements (so the names read
# on[-1], on[0], on[1]); the window of four consecutive nodes wraps onto its
# own start, so every generated window names on[n] twice and the compiler
# sums it to 2*on[n] (TEMPLATE_TERMS_MERGED). Adjacent pairs cost 1.5, and
# the quadratic template wraps from on[1] to on[-1]. All three on breaks
# every window (4 > 3); of the rest, on[-1] and on[1] is best: 3 + 4 - 1.5 =
# 5.5, unique.
def ring_window_terms_merged() -> OptimizationProblem:
    return make_problem_1_3(
        name="ring_window_terms_merged",
        direction="maximize",
        index_sets=[{"name": "node", "elements": [-1, 0, 1], "order": "cyclic"}],
        parameters=[
            {"name": "gain", "indices": ["node"], "values": _rows(1, {-1: 3, 0: 2, 1: 4})}
        ],
        variable_families=[{"name": "on", "indices": ["node"]}],
        linear_term_templates=[
            {"for_each": ["n in node"], "coefficient": "gain[n]", "variable": "on[n]"}
        ],
        quadratic_term_templates=[
            {
                "for_each": ["n in node"],
                "coefficient": -1.5,
                "variable1": "on[n]",
                "variable2": "on[n+1]",
            }
        ],
        constraint_templates=[
            {
                "id": "window",
                "type": "hard",
                "for_each": ["n in node"],
                "terms": [
                    {"coefficient": 1, "variable": "on[n]"},
                    {"coefficient": 1, "variable": "on[n+1]"},
                    {"coefficient": 1, "variable": "on[n+2]"},
                    {"coefficient": 1, "variable": "on[n+3]"},
                ],
                "operator": "<=",
                "rhs": 3,
            }
        ],
    )


# Three tasks over two days. Parameters give a hard cardinality rhs (need),
# a hard linear rhs (cap) and a soft cardinality weight (urgency).
def parameter_rhs_and_weight() -> OptimizationProblem:
    return make_problem_1_3(
        name="parameter_rhs_and_weight",
        direction="minimize",
        index_sets=[
            {"name": "task", "elements": ["t1", "t2", "t3"]},
            {"name": "day", "elements": ["mon", "tue"]},
        ],
        parameters=[
            {
                "name": "cost",
                "indices": ["task", "day"],
                "values": _rows(
                    2,
                    {
                        ("t1", "mon"): 2,
                        ("t1", "tue"): 3,
                        ("t2", "mon"): 1,
                        ("t2", "tue"): 4,
                        ("t3", "mon"): 3,
                        ("t3", "tue"): 1,
                    },
                ),
            },
            {"name": "effort", "indices": ["task"], "values": _rows(1, {"t1": 1, "t2": 2, "t3": 1})},
            {"name": "need", "indices": ["day"], "values": _rows(1, {"mon": 2, "tue": 1})},
            {"name": "cap", "indices": ["day"], "values": _rows(1, {"mon": 3, "tue": 2})},
            {
                "name": "urgency",
                "indices": ["task"],
                "values": _rows(1, {"t1": 4, "t2": 2.5, "t3": 1}),
            },
        ],
        variable_families=[{"name": "do", "indices": ["task", "day"]}],
        linear_term_templates=[
            {
                "for_each": ["t in task", "d in day"],
                "coefficient": "cost[t,d]",
                "variable": "do[t,d]",
            }
        ],
        constraint_templates=[
            {
                "id": "effort_cap",
                "type": "hard",
                "for_each": ["d in day"],
                "terms": [
                    {"for_each": ["t in task"], "coefficient": "effort[t]", "variable": "do[t,d]"}
                ],
                "operator": "<=",
                "rhs": "cap[d]",
            }
        ],
        cardinality_constraint_templates=[
            {
                "id": "staffed",
                "type": "hard",
                "for_each": ["d in day"],
                "variables": [{"for_each": ["t in task"], "variable": "do[t,d]"}],
                "operator": "==",
                "rhs": "need[d]",
            },
            {
                "id": "done",
                "type": "soft",
                "for_each": ["t in task"],
                "variables": [{"for_each": ["d in day"], "variable": "do[t,d]"}],
                "operator": ">=",
                "rhs": 1,
                "weight": "urgency[t]",
            },
        ],
    )


# Integer units per product within an hour budget and a per-product cap
# (rhs a parameter), with diminishing returns (an integer self-product) and
# a binary open family linked to the units, each open product costing a
# fixed amount (a negative parameter value). p2's cap of 3 is its upper
# bound, so that generated constraint is REDUNDANT_CONSTRAINT.
def integer_family() -> OptimizationProblem:
    return make_problem_1_3(
        name="integer_family",
        direction="maximize",
        index_sets=[{"name": "product", "elements": ["p1", "p2"]}],
        parameters=[
            {"name": "profit", "indices": ["product"], "values": _rows(1, {"p1": 5, "p2": 3})},
            {"name": "hours", "indices": ["product"], "values": _rows(1, {"p1": 2, "p2": 1})},
            {"name": "max_units", "indices": ["product"], "values": _rows(1, {"p1": 2, "p2": 3})},
            {"name": "fixed", "indices": ["product"], "values": _rows(1, {"p1": -1, "p2": -2})},
        ],
        variable_families=[
            {
                "name": "units",
                "indices": ["product"],
                "type": "integer",
                "lower_bound": 0,
                "upper_bound": 3,
            },
            {"name": "open", "indices": ["product"], "type": "binary"},
        ],
        linear_term_templates=[
            {"for_each": ["p in product"], "coefficient": "profit[p]", "variable": "units[p]"},
            {"for_each": ["p in product"], "coefficient": "fixed[p]", "variable": "open[p]"},
        ],
        quadratic_term_templates=[
            {
                "for_each": ["p in product"],
                "coefficient": -0.5,
                "variable1": "units[p]",
                "variable2": "units[p]",
            }
        ],
        constraint_templates=[
            {
                "id": "hour_budget",
                "type": "hard",
                "terms": [
                    {"for_each": ["p in product"], "coefficient": "hours[p]", "variable": "units[p]"}
                ],
                "operator": "<=",
                "rhs": 5,
            },
            {
                "id": "unit_cap",
                "type": "hard",
                "for_each": ["p in product"],
                "terms": [{"coefficient": 1, "variable": "units[p]"}],
                "operator": "<=",
                "rhs": "max_units[p]",
            },
            {
                "id": "units_need_open",
                "type": "hard",
                "for_each": ["p in product"],
                "terms": [
                    {"coefficient": 1, "variable": "units[p]"},
                    {"coefficient": -3, "variable": "open[p]"},
                ],
                "operator": "<=",
                "rhs": 0,
            },
        ],
    )


# Soft templates only: a soft at-most-one over everyone (no for_each, so the
