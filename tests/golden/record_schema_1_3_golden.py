"""Record the schema ``1.3`` golden (index sets, parameters, families, templates).

Recorded *after* the templates were implemented, from the working tree
``c69f704`` plus the schema 1.3 changes (spec §14.15). It freezes what the
code does today for a fixed list of ``"version": "1.3"`` template problems
and for a fixed list of documents the expansion refuses, so a later change
cannot move either unnoticed; it does not prove that output correct -- spec
§14.16 and the ``test_template_*`` modules do that (the equivalence tests
hold every expansion against a hand-written explicit oracle). The lists are
spelled out here on purpose (no discovery), every problem is ``1.3``:

* ``examples/tsp_template.json`` (the schema 1.3 example, optimum 8);
* four fixtures of ``tests/fixtures/templates``: the assignment (a 0/1
  parameter in ``where`` leaves ``x[alice,drive]`` unused, so it is left
  out: ``UNUSED_TEMPLATE_VARIABLES``), the shift roster (the rest rule's
  outer index is used only in its member's ``where``), the two-worker
  window (a ``linear`` day set: ``TEMPLATE_BOUNDARY_SKIPPED`` for a
  quadratic term template and a constraint template) and the mixed problem
  (explicit entries naming generated variables, an integer family, a soft
  template whose rhs and weight are parameters, a cardinality rhs that is a
  parameter);
* five problems written for this golden: a ``cyclic`` ring of integer
  elements whose window template wraps onto itself
  (``TEMPLATE_TERMS_MERGED``), parameters as a cardinality rhs, a linear rhs
  and a soft weight, an integer family, soft templates only, and a family
  most of whose variables no template uses (``UNUSED_TEMPLATE_VARIABLES``
  with more names than it lists, plus ``EMPTY_TEMPLATE_EXPANSION``).

Each problem records these sections (see :data:`SECTIONS`):

``expanded``
    ``expand_problem(problem).problem.model_dump()``: the explicit entries
    first, then every generated one, in generation order.
``expansion_warnings``
    The expansion's own warnings as ``[code, path, message]``.
``snapshot``
    ``record_phase3a_golden.snapshot_problem`` of the expanded problem --
    both compiled models, the estimates and the penalty scale -- except that
    its two full validations are taken with
    ``validate_expanded(expand_problem(problem), ...)``, so every path on a
    generated entry is mapped back to its template and carries the
    ``(generated by ...)`` suffix, and the expansion warnings come first.
``exact_solve``
    ``OptimizationService.solve`` of the *template* problem (the service
    expands it) on the ``exact`` backend, for problems whose compiled BQM has
    at most 20 variables; null for the others. The fields kept and dropped
    are those of ``record_compat_golden.section_exact_solve`` (its helpers are
    imported and reused): nothing that changes between runs, machines or
    dependency versions.

A separate part, ``expansion_errors``, records what ``expand_problem``
reports, as ``[code, path, message]``, for documents it refuses (see
:data:`ERROR_DOCUMENTS`): each new error code of spec §14.10 at least once,
the version gate (``FEATURE_REQUIRES_NEWER_VERSION``) twice, both kinds of
``TEMPLATE_EXPANSION_LIMIT`` (the upper bound U and the work W, each under
an explicit small ``max_template_bindings`` so the golden does not follow
the policy default) and two documents whose errors pass the ceiling of 20
per source, so the ``... more errors ... are not listed`` suffix is frozen.

Recording refuses (raises) instead of writing a golden when a problem is not
``1.3``, when its expansion fails, when ``estimate_compiled_variables``
differs from the compiled BQM, when a problem with a known optimum solves to
another value, or when an error document expands without error.

Every value is a plain ``list`` / ``dict`` / ``str`` / ``float`` / ``int`` /
``bool`` / ``None`` so a ``json`` round-trip is exact. Re-record (only ever
intentionally) with::

    .venv/Scripts/python.exe tests/golden/record_schema_1_3_golden.py
"""

