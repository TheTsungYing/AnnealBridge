def _refuse_suspicious(name: str, problem: OptimizationProblem, entry: dict) -> None:
    """Raise rather than freeze an output that looks wrong (see the docstring)."""
    expanded = _expand(problem).problem
    penalty = ScaledPenaltyStrategy().initial_penalty(expanded)
    compiled = BQMCompiler().compile(expanded, penalty).num_variables
    estimated = estimate_compiled_variables(expanded)
    if estimated != compiled:
        raise ValueError(f"{name}: estimated {estimated} != compiled {compiled}")
    if name in KNOWN_OPTIMA:
        solve = entry["exact_solve"]
        if solve is None or solve["status"] != "success":
            raise ValueError(f"{name}: no exact optimum to compare")
        best = solve["solutions"][0]["objective_value"]
        if best != KNOWN_OPTIMA[name]:
            raise ValueError(f"{name}: optimum {best}, expected {KNOWN_OPTIMA[name]}")


def record_problem_1_3(name: str, problem: OptimizationProblem) -> dict:
    if problem.version != VERSION:
        raise ValueError(f"{name}: version {problem.version!r}, expected {VERSION!r}")
    entry: dict[str, Any] = {"version": problem.version}
    for section, snapshot in SECTIONS.items():
        entry[section] = snapshot(problem)
    _refuse_suspicious(name, problem, entry)
    return entry


def record() -> dict:
    if expand_problem(OptimizationProblem.model_validate(_error_base())).errors:
        raise ValueError("the error-document base does not expand")
    refused: dict[str, dict] = {}
    for name, (build, ceiling) in ERROR_DOCUMENTS.items():
        recorded = expansion_errors(build(), ceiling)
        if not recorded["errors"]:
            raise ValueError(f"error document {name!r} expanded without error")
        refused[name] = recorded
    return {
        "recorded_from": RECORDED_FROM,
        "problems": {
            name: record_problem_1_3(name, build()) for name, build in PROBLEMS.items()
        },
        "expansion_errors": refused,
    }


def main() -> None:
    GOLDEN_PATH.write_text(
        json.dumps(record(), indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    print(
        f"recorded {len(PROBLEMS)} problems and {len(ERROR_DOCUMENTS)} error "
        f"documents to {GOLDEN_PATH}"
    )


if __name__ == "__main__":
    main()
