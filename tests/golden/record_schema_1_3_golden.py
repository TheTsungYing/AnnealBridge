def _expand(problem: OptimizationProblem) -> ExpandedProblem:
    expansion = expand_problem(problem)
    if expansion.errors or expansion.problem is None:
        raise ValueError(f"{problem.name}: expansion failed: {_triples(expansion.errors)}")
    return expansion


def _triples(entries) -> list[list[str | None]]:
    return [[entry.code, entry.path, entry.message] for entry in entries]


def section_expanded(problem: OptimizationProblem) -> dict:
    return _expand(problem).problem.model_dump()


def section_expansion_warnings(problem: OptimizationProblem) -> list:
    return _triples(_expand(problem).warnings)


def section_snapshot(problem: OptimizationProblem) -> dict:
    expansion = _expand(problem)
    snapshot = snapshot_problem(expansion.problem)
    # The same two validations, taken on the expansion so the paths are
    # mapped back to the templates (spec §14.11).
    snapshot["validate_full_exact"] = validate_expanded(
        expansion, capabilities=_exact_capabilities()
    ).model_dump(mode="json")
    snapshot["validate_full_cqm_path"] = validate_expanded(
        expansion, model_type="cqm"
    ).model_dump(mode="json")
    return snapshot


def section_exact_solve(problem: OptimizationProblem) -> dict | None:
    """``record_compat_golden.section_exact_solve`` for a template problem.

    The size gate and the infeasibility diagnostics read the expanded
    problem; the solve itself gets the template problem, so the service's
    own expansion is part of what is frozen.
    """
    expanded = _expand(problem).problem
    penalty = ScaledPenaltyStrategy().initial_penalty(expanded)
    if BQMCompiler().compile(expanded, penalty).num_variables > EXACT_MAX_BQM_VARIABLES:
        return None
    on_exact = problem.model_copy(
        update={"solver": problem.solver.model_copy(update={"backend": "exact"})}
    )
    service = OptimizationService(registry=_local_registry(), policy=ExecutionPolicy())
    result = service.solve(on_exact)
    return {
        "status": result.status,
        "backend": result.backend,
        "objective_direction": result.objective_direction,
        "infeasibility_proven": result.infeasibility_proven,
        "optimality_proven": result.optimality_proven,
        "errors": _code_path(result.errors),
        "warnings": _code_path(result.warnings),
        "metadata": (
            None if result.metadata is None else _pick(result.metadata, _METADATA_FIELDS)
        ),
        "attempts": [_pick(attempt, _ATTEMPT_FIELDS) for attempt in result.attempts],
        "solutions": [
            {
                **_pick(solution, _SOLUTION_FIELDS),
                "constraint_evaluations": [
                    _pick(evaluation, _EVALUATION_FIELDS)
                    for evaluation in solution.constraint_evaluations
                ],
            }
            for solution in result.solutions
        ],
        "infeasibility": (
            None
            if result.infeasibility is None
            else _infeasibility(expanded, result.infeasibility)
        ),
    }


