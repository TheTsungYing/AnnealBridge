def _error_base() -> dict:
    """A small valid ``1.3`` document every refused one starts from.

    U = 3 (the family) + 3 (the objective template) + 1 x (1 + 3) (the
    cardinality template) = 10; W = 3 + 3 + 1 + (1 + 2 + 3) = 13.
    """
    return {
        "version": VERSION,
        "name": "expansion error base",
        "index_sets": [{"name": "item", "elements": ["a", "b", "c"]}],
        "parameters": [
            {"name": "value", "indices": ["item"], "values": _rows(1, {"a": 3, "b": 1, "c": 2})}
        ],
        "variable_families": [{"name": "x", "indices": ["item"]}],
        "variables": [],
        "objective": {
            "direction": "maximize",
            "linear_terms": [],
            "linear_term_templates": [
                {"for_each": ["i in item"], "coefficient": "value[i]", "variable": "x[i]"}
            ],
        },
        "constraints": [],
        "cardinality_constraint_templates": [
            {
                "id": "at_most_two",
                "type": "hard",
                "variables": [{"for_each": ["i in item"], "variable": "x[i]"}],
                "operator": "<=",
                "rhs": 2,
            }
        ],
    }


def _edit(change: Callable[[dict], None]) -> Callable[[], dict]:
    def build() -> dict:
        document = _error_base()
        change(document)
        return document

    return build


def _set(path: tuple, value: Any) -> Callable[[dict], None]:
    def change(document: dict) -> None:
        target = document
        for key in path[:-1]:
            target = target[key]
        target[path[-1]] = value

    return change


