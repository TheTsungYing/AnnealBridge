def expansion_errors(document: dict, max_template_bindings: int) -> dict:
    """What ``expand_problem`` reports for ``document``."""
    problem = OptimizationProblem.model_validate(document)
    expansion = expand_problem(problem, max_template_bindings=max_template_bindings)
    return {
        "max_template_bindings": max_template_bindings,
        "limit_exceeded": expansion.limit_exceeded,
        "errors": _triples(expansion.errors),
    }


